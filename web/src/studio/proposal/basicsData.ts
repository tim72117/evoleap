export type Lesson = {
  title: string
  /** 預估學習時間（含影片與實作），例如「約 30 分」 */
  length: string
  /** 這一課結束時能做到的事 */
  objective: string
  /** 實作成果：學員手上會有什麼 */
  result: string
  /** 單課內容（L0／L1 已寫到步驟與提示詞） */
  course?: CourseLesson
  status?: ProductionStatus
  /** 製作的下一步 */
  next?: string
}

/** 由單課資料產生大綱表的一列；標題、時長、目標、成果都取自同一份資料。 */
function fromCourse(c: CourseLesson): Lesson {
  const p = PROGRESS[c.id] ?? {
    status: '大綱完成',
    next: c.id.startsWith('0.') ? '寫腳本' : c.id.startsWith('T') ? '用選定工具實測提示詞後寫腳本' : '決定 L1 用哪一種工具後寫腳本',
  }
  return { title: c.title, length: c.length, objective: c.goal, result: c.deliverable, course: c, ...p }
}

const COURSE_BY_ID = new Map([...L0_LESSONS, ...L1_LESSONS, ...L1T_LESSONS].map((c) => [c.id, c]))
function lesson(id: string): Lesson {
  const c = COURSE_BY_ID.get(id)
  if (!c) throw new Error(`找不到課程 ${id}`)
  return fromCourse(c)
}

