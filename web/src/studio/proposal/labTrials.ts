// 其他課程（和全環節課程清單不重疊的部分）的試做清單：每一堂一份腳本，放在 content/live/lab/<課程>/。
// 試做頁的路由由 routes.tsx 依這份清單產生；清單頁 /studio/trials 列出全部並逐一載入檢查。
// 全環節課程清單的試做另外在 fullCourse.ts（/studio/full-course）。

export type LabTrial = {
  /** 課程名稱（分組用） */
  course: string
  /** 課號，例如 1.1、T2.1 */
  code: string
  title: string
  /** 腳本路徑（相對於 content/live/） */
  script: string
  /** 試做頁網址 */
  path: string
  /** 兒童課用兒童版播放器 */
  player?: 'kids'
  /** 返回的頁面 */
  back: { to: string; label: string }
}

const slug = (code: string) => code.toLowerCase().replace('.', '-')

const group = (
  course: string,
  dir: string,
  base: string,
  back: string,
  items: [string, string][],
  opts: { player?: 'kids'; suffix?: string } = {},
): LabTrial[] =>
  items.map(([code, title]) => ({
    course,
    code,
    title,
    script: `lab/${dir}/${code}.json`,
    path: `${base}/${slug(code)}${opts.suffix ?? ''}`,
    ...(opts.player ? { player: opts.player } : {}),
    back: { to: base, label: `← ${back}` },
  }))

